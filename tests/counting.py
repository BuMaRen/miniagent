def sum(source: str) -> int:
    """
    计算 source 中所有物品的数量总和。

    Args:
        source: 形如 "1:10 2:20 3:30" 的字符串，表示物品编号及其对应的数量。

    Returns:
        所有物品数量的总和。
    """
    total = 0
    for item in source.split():
        try:
            _, quantity = item.split(":")
            total += int(quantity)
        except ValueError:
            continue
    return total

