def lookup_han_dynasty_fact(topic: str) -> str:
    """查询与本篇故事相关的西汉(建元年间)历史/风俗考据条目。

    用于在撰写或评审涉及制度、器物、纪年等细节前先核实史实,避免出现
    "现代常识空降到汉代"式的失真描写(如年号误用、货币用错、宵禁被无视等)。

    Args:
        topic: 想查询的主题关键词,可选值包括: 纪年与建元、货币、长安东市与西市、
            宵禁与街鼓、路引与乡里连坐、服饰与身份、饮食起居、郎官与亭长、
            张骞出使西域、河西走廊与匈奴。传入未收录的关键词会返回可选列表提示。
    """
    if topic in _FACTS:
        return _FACTS[topic]
    available = "、".join(_FACTS)
    return f"未收录该主题的考据条目。可选主题: {available}"


def list_research_topics() -> list[str]:
    """列出当前知识库覆盖的全部考据主题,便于撰写前先扫一眼有哪些可查。"""
    return list(_FACTS)


